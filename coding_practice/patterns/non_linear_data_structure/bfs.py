# Breadth-First Search (BFS) Pattern
# This pattern is used for traversing or searching tree or graph data structures.
# The idea is to explore all the neighbor nodes at the present depth prior to moving on to nodes at the next depth level.
# This can be implemented using a queue (FIFO) data structure.
# BFS is useful for finding the shortest path in unweighted graphs.
# It can also be used to solve problems like finding all connected components in a graph.

