# Dynamic Programming Pattern
# This pattern is used for solving problems by breaking them down into simpler subproblems.
# The idea is to store the results of expensive function calls and reuse them when the same inputs occur again.
# This can significantly reduce the time complexity, especially for problems with overlapping subproblems.
# Dynamic programming is commonly used in optimization problems, such as finding the shortest path or the best way to pack items.

