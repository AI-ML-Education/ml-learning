# Sliding Window Pattern
# This pattern is used for problems involving subarrays or substrings.
# The idea is to maintain a window (a range of elements) that satisfies a certain condition.
# As you iterate through the data, you can expand or contract the window to find the optimal solution.
# Often combines with hash maps or sets to keep track of elements within the window.
# This can often reduce the time complexity from O(n^2) to O(n).
# For example, finding the longest substring without repeating characters can be solved using this pattern.

