# Binary Search Pattern
# This pattern is used for searching in a sorted array or list.
# The idea is to repeatedly divide the search interval in half.
# If the value of the search key is less than the item in the middle of the interval,
# narrow the interval to the lower half. Otherwise, narrow it to the upper half.
# This can reduce the time complexity from O(n) where one scans all elements to O(log n) to reduce the search space.

